// Before/after evidence per section: the published site (BEFORE_URL, e.g. main served locally) next to this
// branch (AFTER_URL), English at 1440 and 390 px, reduced motion so the hero is still. JPEG to keep the
// repository light; an index in Markdown for STATUS.md and the pull request.
//   BEFORE_URL=http://127.0.0.1:8001/ AFTER_URL=http://127.0.0.1:8000/ node tools/qa/before-after.mjs
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { launch } from '../capture/lib.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = path.join(root, 'docs/web-studio/real-product-evidence/before-after');
const before = process.env.BEFORE_URL ?? 'http://127.0.0.1:8001/';
const after = process.env.AFTER_URL ?? 'http://127.0.0.1:8000/';
// [label, section on the published site (or null), section on this branch (or null)]
const PAIRS = [
  ['hero', '#home', '#home'], ['tour', '#platform', '#platform'], ['modules', '#modules', '#modules'],
  ['player-360', null, '#player-360'], ['payments', '#payments', '#payments'], ['compliance', null, '#compliance'],
  ['intelligence', '#intelligence', '#intelligence'], ['security', '#security', '#security'], ['pilot', '#how', '#pilot'],
  ['company', '#company', '#company'], ['contact', '#contact', '#contact'], ['footer', '.rhs-footer', '.rhs-footer'],
];
const WIDTHS = [1440, 390];

await mkdir(outDir, { recursive: true });
const browser = await launch();
const rows = [];
try {
  for (const width of WIDTHS) {
    const pages = {};
    for (const [key, url] of [['before', before], ['after', after]]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 }, deviceScaleFactor: 1, reducedMotion: 'reduce', ...(width < 600 ? { isMobile: true, hasTouch: true } : {}) });
      await page.goto(url, { waitUntil: 'networkidle' });
      await page.evaluate(() => document.fonts.ready);
      await page.evaluate(async () => { for (let y = 0; y < document.body.scrollHeight; y += 600) { scrollTo(0, y); await new Promise(r => setTimeout(r, 30)); } scrollTo(0, 0); });
      await page.waitForLoadState('networkidle');
      // Sticky header and skip link would otherwise be stitched into tall section captures.
      await page.addStyleTag({ content: 'header{position:static!important}.rhs-skip{display:none!important}' });
      pages[key] = page;
    }
    for (const [label, oldSel, newSel] of PAIRS) {
      const files = {};
      for (const [key, selector] of [['before', oldSel], ['after', newSel]]) {
        if (!selector || !(await pages[key].locator(selector).count())) { files[key] = null; continue; }
        const name = `${label}-${width}-${key}.jpg`;
        await writeFile(path.join(outDir, name), await pages[key].locator(selector).first().screenshot({ type: 'jpeg', quality: 72 }));
        files[key] = name;
      }
      rows.push({ label, width, ...files });
      console.log(`${label} @${width}: ${files.before ?? '—'} | ${files.after ?? '—'}`);
    }
    for (const page of Object.values(pages)) await page.close();
  }
} finally { await browser.close(); }
const cell = file => file ? `![](before-after/${file})` : '— (new section)';
const table = ['| Section | Width | Before (main) | After (this branch) |', '|---|---|---|---|', ...rows.map(r => `| ${r.label} | ${r.width} | ${cell(r.before)} | ${cell(r.after)} |`)].join('\n');
await writeFile(path.join(root, 'docs/web-studio/real-product-evidence/before-after.md'), `# Before / after by section\n\nBefore: \`main\` (published site). After: this branch. English, reduced motion. Generated by \`tools/qa/before-after.mjs\`.\n\n${table}\n`);
console.log('Index: docs/web-studio/real-product-evidence/before-after.md');
